test('admin connects POS stock; guest checkout and POS consumption share the same Firebase ledger',async({page,browser,request})=>{
  const require=createRequire(new URL('../../../BelleLocal POS app/functions/package.json',import.meta.url))
  const {initializeApp,getApps}=require('firebase-admin/app'); const {getFirestore}=require('firebase-admin/firestore')
  process.env.FIRESTORE_EMULATOR_HOST='127.0.0.1:8080'
  const app=getApps().find((entry)=>entry.name==='bound-browser') || initializeApp({projectId:'demo-belle-online'},'bound-browser')
  const db=getFirestore(app); const ledger=createStockLedger({db}); const posId='pos-'+randomUUID(); const dress='Bound Browser '+randomUUID().slice(0,8)
  const sku='BOUND-'+randomUUID(); const owner=await ownerToken(request); const headers={Authorization:'Bearer '+owner}
  await db.doc('onlineShopV2/belle-online/pos_products/'+posId).set({name:'POS '+dress,isActive:true,trackingMode:'NONE'})
  await ledger.receive('belle-online',{productId:posId,quantity:2,unitCost:3000},'demo-owner',randomUUID())
  const created=await request.post(api+'admin/products',{headers,data:{name:dress,slug:'bound-browser-'+randomUUID(),status:'published',variants:[{color:'Brown',size:'1',sku,price:5000,active:true}]}})
  expect(created.ok()).toBeTruthy(); const productId=await created.json()
  const productResponse=await request.get(api+'admin/products/'+productId,{headers}); const product=await productResponse.json()
  await login(page); await page.getByRole('tab',{name:'Inventory',exact:true}).click()
  await page.getByLabel('Search name or SKU',{exact:true}).fill(sku)
  await page.getByRole('button',{name:'Connect '+sku,exact:true}).click()
  await page.getByRole('combobox',{name:/^POS product/}).click(); await page.getByRole('option',{name:'POS '+dress,exact:true}).click()
  await page.getByRole('button',{name:'Connect stock',exact:true}).click(); await expect(page.getByRole('dialog')).toBeHidden()
  const row=page.getByRole('row').filter({hasText:sku})
  await expect(row.getByText('Managed in POS',{exact:true})).toBeVisible(); await expect(row.getByRole('cell').nth(2)).toHaveText('2')
  expect((await request.post(api+'admin/inventory',{headers,data:{variantId:product.variants[0].id,delta:1,note:'Bypass'}})).status()).toBe(409)
  expect((await request.post(api+'admin/stock/bind',{data:{public_product_id:productId,public_variant_id:product.variants[0].id,pos_product_id:posId}})).status()).toBe(401)
  const guest=await browser.newContext(); const shop=await guest.newPage()
  await shop.goto('http://127.0.0.1:5173/'); await shop.getByText(dress,{exact:true}).click()
  await expect(shop.getByText('2 available',{exact:true})).toBeVisible()
  await shop.getByRole('button',{name:'Add to cart',exact:true}).click(); await shop.getByRole('link',{name:'View cart',exact:true}).click(); await shop.getByRole('link',{name:'Checkout',exact:true}).click()
  await shop.getByLabel(/\/ Name/).fill('Bound browser buyer'); await shop.getByLabel(/\/ Phone/).fill('09942988167'); await shop.getByLabel(/\/ City/).fill('Yangon'); await shop.getByLabel(/\/ Delivery address/).fill('Private bound delivery address')
  await shop.getByRole('button',{name:'Place order',exact:true}).click(); await expect(shop.getByRole('heading',{name:'Order request received'})).toBeVisible()
  const orders=await request.get(api+'admin/records/orders',{headers}); const order=(await orders.json()).find((entry)=>entry.items.some((item)=>item.product_id===productId))
  expect(order.stock_reservations).toHaveLength(1); expect(order.stock_reservations[0].totalCost).toBe('3000')
  await ledger.reservation('belle-online',{productId:posId,sourceType:'PosOrder',sourceId:'browser-pos-'+randomUUID(),quantity:1},'demo-owner',randomUUID())
  const catalog=await request.get(api+'catalog'); expect((await catalog.json()).find((entry)=>entry.id===productId).variants[0].available).toBe(0)
  const rejected=await request.post(api+'checkout',{data:{request_key:randomUUID(),tracking_token:'e'.repeat(64),customer:{name:'Extra',phone:'09942988167',city:'Yangon',address:'Extra address'},items:[{variant_id:product.variants[0].id,quantity:1}]}})
  expect(rejected.status()).toBe(409)
  for(const status of ['confirmed','packing','shipped','delivered']) expect((await request.post(api+'admin/orders/'+order.id+'/transition',{headers,data:{status,courier:'Courier'}})).ok()).toBeTruthy()
  await shop.reload(); await expect(shop.getByText('Delivered',{exact:true}).first()).toBeVisible()
  const raw=(await db.doc('onlineShopV2/belle-online/products/'+productId).get()).data()
  expect(raw.variants[0].on_hand).toBe(0); expect(raw.variants[0].reserved).toBe(0)
  await page.setViewportSize({width:390,height:844}); await page.reload(); await page.getByLabel('Search name or SKU',{exact:true}).fill(sku)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.screenshot({path:'docs/screenshots/belle-pos-shared-stock.png',fullPage:true}); await guest.close()
})
