import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
const preview='http://127.0.0.1:5176/'
const api='http://127.0.0.1:5001/demo-belle-online/asia-southeast1/onlineShopApi/belle-online/admin/pos/'
async function signIn(page,path){
  await page.goto(preview+path)
  await page.getByRole('textbox',{name:'Email',exact:true}).fill('owner@belle-demo.example')
  await page.getByRole('textbox',{name:'Password',exact:true}).fill('Local-test-only-123!')
  await page.getByRole('button',{name:/Sign in|Login/i}).click()
}
async function headers(request){const response=await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=demo-key',{data:{email:'owner@belle-demo.example',password:'Local-test-only-123!',returnSecureToken:true}});expect(response.ok()).toBeTruthy();const account=await response.json();return {Authorization:'Bearer '+account.idToken}}

test('retained Customers page creates, edits, reports, reloads on mobile and deletes through Firebase',async({page,request})=>{
  test.setTimeout(90000)
  const name='Browser Customer '+randomUUID().slice(0,8),edited=name+' edited',errors=[]
  page.on('pageerror',(error)=>errors.push(error.message));await page.setViewportSize({width:1280,height:900})
  await signIn(page,'#/customers')
  await page.getByRole('button',{name:'Add Customer',exact:true}).click()
  await page.getByLabel('Customer Name',{exact:false}).fill(name)
  await page.getByLabel('Phone',{exact:true}).fill('099999999')
  await page.getByLabel('Address',{exact:true}).fill('Emulator customer street')
  await page.getByLabel('City',{exact:true}).fill('Yangon')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeHidden({timeout:20000})
  await page.getByPlaceholder('Search by name or phone',{exact:true}).fill(name)
  await expect(page.getByRole('button',{name:'View '+name,exact:true})).toBeVisible({timeout:20000})
  await page.getByRole('button',{name:'Actions for '+name,exact:true}).click()
  await page.getByRole('menuitem',{name:'Edit',exact:true}).click()
  await page.getByLabel('Customer Name',{exact:false}).fill(edited)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeHidden({timeout:20000})
  await page.getByRole('button',{name:'View '+edited,exact:true}).click()
  const details=page.getByRole('dialog',{name:/^Customer Details/})
  await expect(details.getByText('Emulator customer street',{exact:true})).toBeVisible()
  await expect(details.getByRole('button',{name:'Report',exact:true})).toBeVisible()
  await expect(details.getByText('Transaction Summary',{exact:true})).toBeVisible({timeout:20000})
  const auth=await headers(request),listed=await request.get(api+'customers?search='+encodeURIComponent(edited),{headers:auth})
  expect(listed.ok()).toBeTruthy();const customer=(await listed.json()).customers[0]
  const report=await request.get(api+'customers/'+customer.id+'/transaction-report',{headers:auth})
  expect(report.ok()).toBeTruthy();expect((await report.json()).summary.invoiceCount).toBe(0)
  await page.screenshot({path:'docs/screenshots/retails-customer-details.png',fullPage:true})
  await details.getByRole('button',{name:'Close Customer Details',exact:true}).click()
  await page.setViewportSize({width:390,height:844});await page.reload()
  await page.getByPlaceholder('Search by name or phone',{exact:true}).fill(edited)
  await expect(page.getByRole('button',{name:'View '+edited,exact:true})).toBeVisible({timeout:20000})
  await page.getByRole('button',{name:'View '+edited,exact:true}).click()
  await expect(page).toHaveURL(new RegExp('#/customers/'+customer.id+'$'))
  await expect(page.getByText('Customer Details',{exact:true})).toBeVisible()
  await expect(page.getByText('Emulator customer street',{exact:true})).toBeVisible({timeout:20000})
  await expect(page.getByText('Transaction Summary',{exact:true})).toBeVisible({timeout:20000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.screenshot({path:'docs/screenshots/retails-customer-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Customer actions',exact:true}).click()
  await page.getByRole('menuitem',{name:'Delete',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Delete',exact:true}).click()
  await expect(page).toHaveURL(/#\/customers$/)
  expect((await request.get(api+'customers/'+customer.id,{headers:auth})).status()).toBe(404)
  expect(errors).toEqual([])
})

test('retained mobile Add Supplier form creates a trusted payable invoice and invoice list reloads from Firebase',async({page,request})=>{
  test.setTimeout(90000)
  const name='Browser Supplier '+randomUUID().slice(0,8),invoice='UI-'+randomUUID(),errors=[]
  page.on('pageerror',(error)=>errors.push(error.message));await page.setViewportSize({width:390,height:844})
  await signIn(page,'#/suppliers/add')
  await expect(page.getByPlaceholder('Enter supplier name',{exact:true})).toBeVisible({timeout:20000})
  await page.getByPlaceholder('Enter supplier name',{exact:true}).fill(name)
  await page.getByPlaceholder('Enter phone number',{exact:true}).fill('099999999')
  await page.getByPlaceholder('Enter invoice number',{exact:true}).fill(invoice)
  await page.getByPlaceholder('Enter delivery name',{exact:true}).fill('Demo truck')
  await page.getByPlaceholder('Enter delivery phone',{exact:true}).fill('091234567')
  await page.locator('input[type="date"]').nth(0).fill('2026-10-11')
  await page.locator('input[type="date"]').nth(1).fill('2026-10-20')
  await page.getByPlaceholder('Enter amount',{exact:true}).fill('50000')
  await page.getByRole('button',{name:'Add Supplier',exact:true}).click()
  await expect(page).toHaveURL(/#\/suppliers$/,{timeout:20000})
  await expect(page.getByText(name,{exact:true})).toBeVisible({timeout:20000})
  const auth=await headers(request),list=await request.get(api+'supplier-delivery-records?search='+encodeURIComponent(invoice),{headers:auth})
  expect(list.ok()).toBeTruthy();const record=(await list.json()).records[0]
  expect(record.supplierName).toBe(name);expect(record.receiverName).toBeTruthy();expect(record.remaining).toBe(50000)
  expect(record.invoiceStatus).toBe('Credit')
  await page.reload();await expect(page.getByText(name,{exact:true})).toBeVisible({timeout:20000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.screenshot({path:'docs/screenshots/retails-supplier-mobile.png',fullPage:true})
  await page.goto(preview+'#/suppliers/add?edit='+record.id)
  await expect(page.getByPlaceholder('Enter supplier name',{exact:true})).toHaveValue(name,{timeout:20000})
  await page.getByPlaceholder('Enter amount',{exact:true}).fill('45000')
  await page.getByRole('button',{name:'Save Supplier',exact:true}).click()
  await expect(page).toHaveURL(/#\/suppliers$/,{timeout:20000})
  const changed=await request.get(api+'supplier-delivery-records/'+record.id,{headers:auth})
  expect((await changed.json()).record.amount).toBe(45000)
  expect(errors).toEqual([])
})
