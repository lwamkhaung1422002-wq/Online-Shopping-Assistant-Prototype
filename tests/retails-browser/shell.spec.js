test('Retails Category Management creates, renames and removes records through the Firebase API',async({page,request})=>{
  const name='Retails Category '+randomUUID().slice(0,8); const renamed=name+' edited'
  const errors=[]; page.on('pageerror',(error)=>errors.push(error.message))
  // Replay the observed failure: the initial read arrives after the post-save
  // read. A committed category must remain visible without a page reload.
  let releaseInitial,initialCaptured,initialDelivered,reads=0
  const holdInitial=new Promise(resolve=>{releaseInitial=resolve})
  const captured=new Promise(resolve=>{initialCaptured=resolve})
  const delivered=new Promise(resolve=>{initialDelivered=resolve})
  await page.route('**/admin/pos/categories',async(route)=>{
    if(route.request().method()!=='GET'){await route.continue();return}
    reads++
    if(reads===1){const response=await route.fetch();expect(response.ok()).toBeTruthy();initialCaptured();await holdInitial;await route.fulfill({response});initialDelivered();return}
    const response=await route.fetch();expect(response.ok()).toBeTruthy();await route.fulfill({response});releaseInitial()
  })
  await page.goto('http://127.0.0.1:5176/#/settings/categories')
  await page.getByRole('textbox',{name:'Email',exact:true}).fill('owner@belle-demo.example')
  await page.getByRole('textbox',{name:'Password',exact:true}).fill('Local-test-only-123!')
  await page.getByRole('button',{name:/Sign in|Login/i}).click()
  await expect(page.getByText('Category Management',{exact:true})).toBeVisible({timeout:20000})
  await captured
  await page.getByRole('button',{name:'Add Category',exact:true}).click()
  await page.getByLabel('Category name',{exact:true}).fill(name)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await delivered
  await expect(page.getByRole('button',{name:'Edit '+name,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Edit '+name,exact:true}).click()
  await page.getByLabel('Category name',{exact:true}).fill(renamed)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.getByRole('button',{name:'Edit '+renamed,exact:true})).toBeVisible()
  const signIn=await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=demo-key',{data:{email:'owner@belle-demo.example',password:'Local-test-only-123!',returnSecureToken:true}})
  expect(signIn.ok()).toBeTruthy(); const headers={Authorization:'Bearer '+(await signIn.json()).idToken}
  const api='http://127.0.0.1:5001/demo-belle-online/asia-southeast1/onlineShopApi/belle-online/admin/pos/categories'
  const list=await request.get(api,{headers}); expect(list.ok()).toBeTruthy()
  const category=(await list.json()).categories.find((entry)=>entry.name===renamed)
  expect(category._count.products).toBe(0)
  await page.reload(); await expect(page.getByRole('button',{name:'Delete '+renamed,exact:true})).toBeVisible({timeout:20000})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  await page.screenshot({path:'docs/screenshots/retails-categories-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Delete '+renamed,exact:true}).click()
  await expect(page.getByRole('button',{name:'Delete '+renamed,exact:true})).toHaveCount(0)
  const after=await request.get(api,{headers}); expect((await after.json()).categories.some((entry)=>entry.id===category.id)).toBeFalsy()
  expect(errors).toEqual([])
})

test('Retails Add Product and Stock In pages save actual Firebase catalogue, receipts, sources and weighted costs',async({page,request})=>{
  test.setTimeout(180000)
  const name='Retails Product '+randomUUID().slice(0,8);const sku='UI-'+randomUUID()
  const errors=[];page.on('pageerror',(error)=>errors.push(error.message))
  await page.goto('http://127.0.0.1:5176/#/stock/add')
  await page.getByRole('textbox',{name:'Email',exact:true}).fill('owner@belle-demo.example')
  await page.getByRole('textbox',{name:'Password',exact:true}).fill('Local-test-only-123!')
  await page.getByRole('button',{name:/Sign in|Login/i}).click()
  await expect(page.getByRole('button',{name:'Save Product',exact:true})).toBeVisible({timeout:20000})
  const field=(label)=>page.getByText(label,{exact:true}).locator('..').locator('..').locator('input').first()
  await page.getByPlaceholder('Enter product name',{exact:true}).fill(name)
  await page.getByPlaceholder('Enter...',{exact:true}).fill(sku)
  await page.getByRole('combobox',{name:'Base Unit',exact:true}).click()
  await page.getByRole('option',{name:'Piece',exact:true}).click()
  await field('Cost Price').fill('3000');await field('Selling Price').fill('5000');await field('Stock Quantity').fill('2.5')
  await field('Supplier (Optional)').fill('Browser supplier');await field('Supplier Invoice').fill('Browser opening invoice')
  await page.getByRole('button',{name:'Save Product',exact:true}).click()
  await expect(page).toHaveURL(/#\/stock$/,{timeout:20000})
  await page.getByPlaceholder('Search product, supplier or invoice...',{exact:true}).fill(sku)
  await expect(page.getByRole('button',{name:'Actions for '+name,exact:true})).toBeVisible({timeout:20000})
  const signIn=await request.post('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=demo-key',{data:{email:'owner@belle-demo.example',password:'Local-test-only-123!',returnSecureToken:true}})
  expect(signIn.ok()).toBeTruthy();const headers={Authorization:'Bearer '+(await signIn.json()).idToken}
  const api='http://127.0.0.1:5001/demo-belle-online/asia-southeast1/onlineShopApi/belle-online/admin/pos/'
  const listed=await request.get(api+'products?search='+encodeURIComponent(sku),{headers});expect(listed.ok()).toBeTruthy()
  const product=(await listed.json()).products[0];expect(product.currentStock).toBe(2.5);expect(product.units[0].unit.name).toBe('Piece')
  await page.goto('http://127.0.0.1:5176/#/stock/movement/add')
  await page.getByPlaceholder('Search product or enter barcode',{exact:true}).fill(name)
  await page.getByPlaceholder('Search product or enter barcode',{exact:true}).press('ArrowDown');await page.getByPlaceholder('Search product or enter barcode',{exact:true}).press('Enter')
  await expect(page.getByText('Current Stock: 2.5 Piece',{exact:true})).toBeVisible()
  await page.getByLabel('Quantity *',{exact:true}).fill('1.5');await page.getByLabel('Cost Price *',{exact:true}).fill('4000')
  await page.getByLabel('Invoice / Reference No. (Optional)',{exact:true}).fill('Browser stock in invoice')
  await page.getByRole('button',{name:'Save Stock In',exact:true}).click()
  await expect(page).toHaveURL(/#\/stock$/,{timeout:20000})
  const saved=await request.get(api+'products/'+product.id,{headers});expect(saved.ok()).toBeTruthy()
  const detail=(await saved.json()).product;expect(detail.currentStock).toBe(4);expect(detail.cost).toBe(3375)
  const sources=await request.get(api+'products/'+product.id+'/source-history',{headers});expect((await sources.json()).sources).toHaveLength(2)
  await page.goto('http://127.0.0.1:5176/#/stock/'+product.id)
  await expect(page.getByText(name,{exact:true}).first()).toBeVisible({timeout:20000})
  expect(errors).toEqual([])
  await page.screenshot({path:'docs/screenshots/retails-product-stock-in.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  const reloadedProduct=page.waitForResponse(response=>response.url()===api+'products/'+product.id&&response.request().method()==='GET')
  await page.reload();expect((await reloadedProduct).status()).toBe(200)
  await expect(page.getByText(name,{exact:true}).first()).toBeVisible({timeout:40000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  const movementHeading=await page.getByText('Recent Stock Movements',{exact:true}).boundingBox()
  const viewAll=await page.getByText('View All',{exact:true}).boundingBox()
  expect(movementHeading.x+movementHeading.width).toBeLessThanOrEqual(viewAll.x)
  const skuLabel=await page.getByText('SKU',{exact:true}).boundingBox()
  const skuValue=await page.getByText(sku,{exact:true}).boundingBox()
  expect(skuLabel.x+skuLabel.width).toBeLessThan(skuValue.x)
  await page.screenshot({path:'docs/screenshots/retails-product-mobile.png',fullPage:true})
  await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button',{name:'Edit product',exact:true}).click()
  await expect(page.getByPlaceholder('Enter product name',{exact:true})).toHaveValue(name,{timeout:20000})
  await expect(page.getByRole('combobox',{name:'Base Unit',exact:true})).toBeDisabled()
  const editedName=name+' edited'
  await page.getByPlaceholder('Enter product name',{exact:true}).fill(editedName)
  await field('Supplier (Optional)').fill('Edited browser supplier')
  await page.getByRole('button',{name:'Save Changes',exact:true}).click()
  await expect(page).toHaveURL(new RegExp('#/stock/'+product.id+'$'),{timeout:20000})
  await expect(page.getByText(editedName,{exact:true}).first()).toBeVisible({timeout:20000})
  const afterEdit=(await (await request.get(api+'products/'+product.id,{headers})).json()).product
  expect(afterEdit.version).toBe(2);expect(afterEdit.currentStock).toBe(4);expect(afterEdit.cost).toBe(3375)
  const updatedSources=(await (await request.get(api+'products/'+product.id+'/source-history',{headers})).json()).sources
  expect(updatedSources.some((source)=>source.supplierName==='Edited browser supplier')).toBeTruthy()
  expect(errors).toEqual([])
  await page.screenshot({path:'docs/screenshots/retails-product-edited.png',fullPage:true})
})
